const std = @import("std");
const ir = @import("../ir/ir.zig");

/// Emit GAS x86_64 AT&T assembly for a Jog IR program.
/// Calling convention (Jog ABI v0): same as SysV for scalars/pointers —
/// args in rdi,rsi,rdx,rcx,r8,r9; return in rax; callee-saved rbx,r12-r15,rbp.
/// C `extern` uses the same SysV rules. Aggregates TBD.
pub fn emit(allocator: std.mem.Allocator, program: *const ir.Program, writer: anytype) !void {
    try writer.writeAll("# generated by jog v2 — no C intermediate\n");
    try writer.writeAll(".intel_syntax noprefix\n");
    try writer.writeAll(".text\n");

    for (program.callees) |c| {
        if (c.kind == .extern_c) {
            try writer.print(".extern {s}\n", .{c.name});
        }
    }

    for (program.funcs) |f| {
        if (f.exported) {
            try writer.print(".globl {s}\n", .{mangle(f.name)});
            try writer.print(".type {s}, @function\n", .{mangle(f.name)});
        }
        try writer.print("{s}:\n", .{mangle(f.name)});
        // prologue
        try writer.writeAll("  push rbp\n");
        try writer.writeAll("  mov rbp, rsp\n");
        const frame: u32 = (f.nlocals + 1) * 8; // align
        const aligned = (frame + 15) & ~@as(u32, 15);
        if (aligned > 0) try writer.print("  sub rsp, {d}\n", .{aligned});

        // move params from SysV regs into slots
        const regs = [_][]const u8{ "rdi", "rsi", "rdx", "rcx", "r8", "r9" };
        var pi: u32 = 0;
        while (pi < f.nparams and pi < regs.len) : (pi += 1) {
            try writer.print("  mov qword ptr [rbp - {d}], {s}\n", .{ (pi + 1) * 8, regs[pi] });
        }

        const ninst = f.insts.len;
        for (f.insts, 0..) |inst, ii| {
            try writer.print(".L{s}_{d}:\n", .{ mangle(f.name), ii });
            try emitInst(writer, program, f.name, ninst, inst);
        }

        try writer.print(".L{s}_end:\n", .{mangle(f.name)});
        try writer.writeAll("  mov rsp, rbp\n");
        try writer.writeAll("  pop rbp\n");
        try writer.writeAll("  ret\n");
        try writer.writeAll("\n");
    }

    if (program.globals.len > 0) {
        try writer.writeAll(".section .data\n");
        try writer.writeAll(".align 8\n");
        for (program.globals, 0..) |g, i| {
            try writer.print(".globl jog_global_{d}\n", .{i});
            try writer.print("jog_global_{d}:\n", .{i});
            try writer.print("  .quad {d}\n", .{g.init_bits});
            _ = g.name;
            _ = g.mutable;
            _ = g.is_float;
        }
    }

    try writer.writeAll(".section .rodata\n");
    try writer.writeAll(".align 8\n");
    for (program.vtables, 0..) |vt, i| {
        _ = vt.symbol;
        try writer.print("jog_vt_{d}:\n", .{i});
        for (vt.methods) |m| {
            try writer.print("  .quad {s}\n", .{m});
        }
    }
    try writer.writeAll("jog_narrow_msg:\n");
    try writer.writeAll("  .ascii \"panic: narrow cast overflow\\n\"\n");
    try writer.writeAll("jog_narrow_msg_len = . - jog_narrow_msg\n");
    for (program.strings, 0..) |s, i| {
        try writer.print("jog_str_{d}:\n", .{i});
        try writer.writeAll("  .byte ");
        for (s, 0..) |b, bi| {
            if (bi > 0) try writer.writeAll(", ");
            try writer.print("{d}", .{b});
        }
        if (s.len == 0) try writer.writeAll("0");
        try writer.writeAll("\n");
    }
    _ = allocator;
}

fn mangle(name: []const u8) []const u8 {
    // Jog names are already asm-safe for the subset
    return name;
}

fn slot(off: u32) u32 {
    return (off + 1) * 8;
}

fn label(writer: anytype, fname: []const u8, ninst: usize, target: i64) !void {
    if (target < 0 or @as(usize, @intCast(target)) >= ninst) {
        try writer.print(".L{s}_end", .{mangle(fname)});
    } else {
        try writer.print(".L{s}_{d}", .{ mangle(fname), target });
    }
}

fn emitInst(writer: anytype, prog: *const ir.Program, fname: []const u8, ninst: usize, inst: ir.Inst) !void {
    switch (inst.op) {
        .iconst => {
            try writer.print("  mov rax, {d}\n", .{inst.aux});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .fconst => {
            // aux holds IEEE754 bit pattern of f64
            try writer.print("  mov rax, {d}\n", .{inst.aux});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .saddr => {
            if (inst.aux < 0) {
                // function address: aux = -1 - callee_index
                const cid: usize = @intCast(-1 - inst.aux);
                const callee = prog.callees[cid];
                try writer.print("  lea rax, [rip + {s}]\n", .{callee.name});
            } else {
                try writer.print("  lea rax, [rip + jog_str_{d}]\n", .{inst.aux});
            }
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .slen => {
            const len = prog.strings[@intCast(inst.aux)].len;
            try writer.print("  mov rax, {d}\n", .{len});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .copy => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .load => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  mov rax, qword ptr [rax]\n");
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .load8 => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  movzx eax, byte ptr [rax]\n");
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .store => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov rcx, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.writeAll("  mov qword ptr [rax], rcx\n");
        },
        .store8 => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov rcx, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.writeAll("  mov byte ptr [rax], cl\n");
        },
        .lea_slot => {
            try writer.print("  lea rax, [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .narrow => {
            // panic if bits above aux are set; then zero-extend into rax.
            // Note: `and rax, imm32` sign-extends the immediate, so 0xffffffff is
            // unusable as a 32-bit mask — use mov/movzx instead (JOG-89).
            const bits: u6 = @intCast(inst.aux);
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  mov rcx, rax\n");
            try writer.print("  shr rcx, {d}\n", .{bits});
            try writer.print("  jz .Lnarrow_ok_{s}_{d}\n", .{ mangle(fname), inst.dst });
            try writer.writeAll("  lea rdi, [rip + jog_narrow_msg]\n");
            try writer.writeAll("  mov esi, 28\n");
            try writer.writeAll("  call jogrt_panic\n");
            try writer.writeAll("  ud2\n");
            try writer.print(".Lnarrow_ok_{s}_{d}:\n", .{ mangle(fname), inst.dst });
            if (bits >= 64) {
                // no-op
            } else if (bits == 32) {
                try writer.writeAll("  mov eax, eax\n");
            } else if (bits == 16) {
                try writer.writeAll("  movzx eax, ax\n");
            } else if (bits == 8) {
                try writer.writeAll("  movzx eax, al\n");
            } else if (bits == 1) {
                try writer.writeAll("  and eax, 1\n");
            } else {
                const mask: u64 = (@as(u64, 1) << bits) - 1;
                try writer.print("  mov rcx, {d}\n", .{mask});
                try writer.writeAll("  and rax, rcx\n");
            }
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .gload => {
            try writer.print("  mov rax, qword ptr [rip + jog_global_{d}]\n", .{inst.aux});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .gstore => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov qword ptr [rip + jog_global_{d}], rax\n", .{inst.aux});
        },
        .add => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  add rax, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .sub => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  sub rax, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .mul => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  imul rax, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .div => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  cqo\n");
            try writer.print("  idiv qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .rem => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  cqo\n");
            try writer.print("  idiv qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rdx\n", .{slot(inst.dst)});
        },
        .fadd, .fsub, .fmul, .fdiv => {
            try writer.print("  movsd xmm0, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            const mop = switch (inst.op) {
                .fadd => "addsd",
                .fsub => "subsd",
                .fmul => "mulsd",
                .fdiv => "divsd",
                else => unreachable,
            };
            try writer.print("  {s} xmm0, qword ptr [rbp - {d}]\n", .{ mop, slot(inst.src1) });
            try writer.print("  movsd qword ptr [rbp - {d}], xmm0\n", .{slot(inst.dst)});
        },
        .and_op, .or_op => {
            // Lowered to short-circuit control flow in IR; should not reach asm.
            try writer.writeAll("  ud2\n");
        },
        .bit_and => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  and rax, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .bit_or => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  or rax, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .bit_xor => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  xor rax, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .shl => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov rcx, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.writeAll("  shl rax, cl\n");
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .shr => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov rcx, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.writeAll("  shr rax, cl\n");
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .eq, .ne, .lt, .le => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  cmp rax, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            const set = switch (inst.op) {
                .eq => "sete",
                .ne => "setne",
                .lt => "setl",
                .le => "setle",
                else => unreachable,
            };
            try writer.print("  {s} al\n", .{set});
            try writer.writeAll("  movzx rax, al\n");
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .neg => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  neg rax\n");
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .bit_not => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  not rax\n");
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .call => {
            const cid: usize = @intCast(inst.aux);
            const callee = prog.callees[cid];
            const use_sysv_float = callee.kind == .extern_c and (callee.float_ret or callee.float_args != 0);
            if (use_sysv_float) {
                // System V AMD64: integer/pointer in GPR sequence; floats in xmm0+.
                const gprs = [_][]const u8{ "rdi", "rsi", "rdx", "rcx", "r8", "r9" };
                const xmms = [_][]const u8{ "xmm0", "xmm1", "xmm2", "xmm3", "xmm4", "xmm5", "xmm6", "xmm7" };
                var gi: u8 = 0;
                var fi: u8 = 0;
                var i: u8 = 0;
                while (i < inst.arity and i < 8) : (i += 1) {
                    const is_f = (callee.float_args & (@as(u8, 1) << @intCast(i))) != 0;
                    if (is_f) {
                        if (fi < xmms.len) {
                            try writer.print("  movsd {s}, qword ptr [rbp - {d}]\n", .{ xmms[fi], slot(inst.args[i]) });
                            fi += 1;
                        }
                    } else if (gi < gprs.len) {
                        try writer.print("  mov {s}, qword ptr [rbp - {d}]\n", .{ gprs[gi], slot(inst.args[i]) });
                        gi += 1;
                    }
                }
                try writer.print("  call {s}\n", .{callee.name});
                if (inst.dst != ir.none) {
                    if (callee.float_ret) {
                        try writer.print("  movsd qword ptr [rbp - {d}], xmm0\n", .{slot(inst.dst)});
                    } else {
                        try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
                    }
                }
            } else {
                const regs = [_][]const u8{ "rdi", "rsi", "rdx", "rcx", "r8", "r9" };
                var i: u8 = 0;
                while (i < inst.arity and i < regs.len) : (i += 1) {
                    try writer.print("  mov {s}, qword ptr [rbp - {d}]\n", .{ regs[i], slot(inst.args[i]) });
                }
                try writer.print("  call {s}\n", .{callee.name});
                if (inst.dst != ir.none) {
                    try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
                }
            }
        },
        .icall => {
            const regs = [_][]const u8{ "rdi", "rsi", "rdx", "rcx", "r8", "r9" };
            var i: u8 = 0;
            while (i < inst.arity and i < regs.len) : (i += 1) {
                try writer.print("  mov {s}, qword ptr [rbp - {d}]\n", .{ regs[i], slot(inst.args[i]) });
            }
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  call rax\n");
            if (inst.dst != ir.none) {
                try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
            }
        },
        .vtaddr => {
            try writer.print("  lea rax, [rip + jog_vt_{d}]\n", .{inst.aux});
            try writer.print("  mov qword ptr [rbp - {d}], rax\n", .{slot(inst.dst)});
        },
        .ret => {
            if (inst.src0 != ir.none) {
                try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            } else {
                try writer.writeAll("  xor eax, eax\n");
            }
            try writer.print("  jmp .L{s}_end\n", .{mangle(fname)});
        },
        .jmp => {
            try writer.writeAll("  jmp ");
            try label(writer, fname, ninst, inst.aux);
            try writer.writeAll("\n");
        },
        .jz => {
            try writer.print("  mov rax, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.writeAll("  test rax, rax\n");
            try writer.writeAll("  jz ");
            try label(writer, fname, ninst, inst.aux);
            try writer.writeAll("\n");
        },
        .panic => {
            try writer.print("  mov rdi, qword ptr [rbp - {d}]\n", .{slot(inst.src0)});
            try writer.print("  mov rsi, qword ptr [rbp - {d}]\n", .{slot(inst.src1)});
            try writer.writeAll("  call jogrt_panic\n");
            try writer.writeAll("  ud2\n");
        },
    }
}
