const std = @import("std");
const ir = @import("../ir/ir.zig");

/// Emit C99 from Jog IR for the emcc / wasm32-emscripten path.
/// Slots are int64_t (same as the native IR model). Pointers/floats are
/// cast at extern call edges. No coroutine stack switch — use runtime stubs.
pub fn emit(allocator: std.mem.Allocator, program: *const ir.Program, writer: anytype) !void {
    _ = allocator;
    try writer.writeAll("/* generated by jog v2 — wasm32-emscripten (IR→C→emcc) */\n");
    try writer.writeAll("#include <stdint.h>\n");
    try writer.writeAll("#include <stdlib.h>\n");
    try writer.writeAll("#include <string.h>\n");
    try writer.writeAll("#include \"jogrt.h\"\n\n");

    // Extern prototypes use intptr_t so wasm32 (emcc) matches C/SDL ABI
    // (i32 pointers/ints). Float edges use double. Slots stay int64_t.
    for (program.callees) |c| {
        if (c.kind != .extern_c) continue;
        if (c.float_ret) {
            try writer.print("extern double {s}(", .{c.name});
        } else {
            try writer.print("extern intptr_t {s}(", .{c.name});
        }
        // Arity unknown at decl time for all call sites; emit a permissive
        // K&R-style empty param list and cast at each call.
        try writer.writeAll(");\n");
    }
    try writer.writeAll("\n");

    // Forward decls for Jog functions (and exports). `main` is C `int` for emcc.
    for (program.funcs) |f| {
        if (std.mem.eql(u8, f.name, "main")) {
            try writer.writeAll("int main(void);\n");
            continue;
        }
        try writer.print("int64_t {s}(", .{mangle(f.name)});
        var pi: u32 = 0;
        while (pi < f.nparams) : (pi += 1) {
            if (pi > 0) try writer.writeAll(", ");
            try writer.print("int64_t a{d}", .{pi});
        }
        if (f.nparams == 0) try writer.writeAll("void");
        try writer.writeAll(");\n");
    }
    try writer.writeAll("\n");

    // Globals (scalar or object multi-slot)
    for (program.globals, 0..) |g, i| {
        if (g.nquads <= 1) {
            try writer.print("int64_t jog_global_{d} = {d}; /* {s} */\n", .{ i, g.init_bits, g.name });
        } else {
            try writer.print("int64_t jog_global_{d}[{d}] = {{ {d}", .{ i, g.nquads, g.init_bits });
            var qi: u32 = 1;
            while (qi < g.nquads) : (qi += 1) try writer.writeAll(", 0");
            try writer.print(" }}; /* object {s} */\n", .{g.name});
        }
        _ = g.is_object;
    }
    if (program.globals.len > 0) try writer.writeAll("\n");

    // Vtables
    for (program.vtables, 0..) |vt, i| {
        try writer.print("static void *jog_vt_{d}[] = {{", .{i});
        for (vt.methods, 0..) |m, mi| {
            if (mi > 0) try writer.writeAll(", ");
            try writer.print("(void*){s}", .{m});
        }
        try writer.writeAll("};\n");
        _ = vt.symbol;
    }
    if (program.vtables.len > 0) try writer.writeAll("\n");

    // Strings
    for (program.strings, 0..) |s, i| {
        try writer.print("static const unsigned char jog_str_{d}[] = {{", .{i});
        for (s, 0..) |b, bi| {
            if (bi > 0) try writer.writeAll(", ");
            try writer.print("{d}", .{b});
        }
        if (s.len == 0) {
            try writer.writeAll("0");
        } else {
            try writer.writeAll(", 0");
        }
        try writer.writeAll("};\n");
    }
    if (program.strings.len > 0) try writer.writeAll("\n");

    try writer.writeAll("static const char jog_narrow_msg[] = \"panic: narrow cast overflow\\n\";\n\n");

    for (program.funcs) |f| {
        const is_main = std.mem.eql(u8, f.name, "main");
        if (f.exported) {
            try writer.writeAll("/* @export */\n");
        }
        if (is_main) {
            try writer.writeAll("int main(void) {\n");
        } else {
            try writer.print("int64_t {s}(", .{mangle(f.name)});
            var pi: u32 = 0;
            while (pi < f.nparams) : (pi += 1) {
                if (pi > 0) try writer.writeAll(", ");
                try writer.print("int64_t a{d}", .{pi});
            }
            if (f.nparams == 0) try writer.writeAll("void");
            try writer.writeAll(") {\n");
        }
        const nslots = if (f.nlocals < 1) 1 else f.nlocals;
        try writer.print("  int64_t s[{d}];\n", .{nslots});
        try writer.writeAll("  memset(s, 0, sizeof s);\n");
        if (!is_main) {
            var pi: u32 = 0;
            while (pi < f.nparams) : (pi += 1) {
                try writer.print("  s[{d}] = a{d};\n", .{ pi, pi });
            }
        }

        const ninst = f.insts.len;
        for (f.insts, 0..) |inst, ii| {
            try writer.print("L{s}_{d}:;\n", .{ mangle(f.name), ii });
            try emitInst(writer, program, f.name, ninst, inst, is_main);
        }
        try writer.print("L{s}_end:;\n", .{mangle(f.name)});
        try writer.writeAll("  return 0;\n");
        try writer.writeAll("}\n\n");
    }
}

fn mangle(name: []const u8) []const u8 {
    return name;
}

fn labelName(buf: []u8, fname: []const u8, ninst: usize, target: i64) ![]const u8 {
    if (target < 0 or @as(usize, @intCast(target)) >= ninst) {
        return try std.fmt.bufPrint(buf, "L{s}_end", .{mangle(fname)});
    }
    return try std.fmt.bufPrint(buf, "L{s}_{d}", .{ mangle(fname), target });
}

fn emitInst(writer: anytype, prog: *const ir.Program, fname: []const u8, ninst: usize, inst: ir.Inst, is_main: bool) !void {
    var lbuf: [128]u8 = undefined;
    switch (inst.op) {
        .iconst => try writer.print("  s[{d}] = {d}LL;\n", .{ inst.dst, inst.aux }),
        .fconst => try writer.print("  s[{d}] = {d}LL; /* f64 bits */\n", .{ inst.dst, inst.aux }),
        .saddr => {
            if (inst.aux < 0) {
                const cid: usize = @intCast(-1 - inst.aux);
                const callee = prog.callees[cid];
                try writer.print("  s[{d}] = (int64_t)(intptr_t)(void*){s};\n", .{ inst.dst, callee.name });
            } else {
                try writer.print("  s[{d}] = (int64_t)(intptr_t)(void*)jog_str_{d};\n", .{ inst.dst, inst.aux });
            }
        },
        .slen => {
            const len = prog.strings[@intCast(inst.aux)].len;
            try writer.print("  s[{d}] = {d}LL;\n", .{ inst.dst, len });
        },
        .copy => try writer.print("  s[{d}] = s[{d}];\n", .{ inst.dst, inst.src0 }),
        .load => try writer.print("  s[{d}] = *(volatile int64_t*)(intptr_t)s[{d}];\n", .{ inst.dst, inst.src0 }),
        .load8 => try writer.print("  s[{d}] = (int64_t)*(volatile uint8_t*)(intptr_t)s[{d}];\n", .{ inst.dst, inst.src0 }),
        .store => {
            try writer.print("  *(volatile int64_t*)(intptr_t)s[{d}] = s[{d}];\n", .{ inst.src0, inst.src1 });
        },
        .store8 => {
            try writer.print("  *(volatile uint8_t*)(intptr_t)s[{d}] = (uint8_t)s[{d}];\n", .{ inst.src0, inst.src1 });
        },
        .lea_slot => try writer.print("  s[{d}] = (int64_t)(intptr_t)&s[{d}];\n", .{ inst.dst, inst.src0 }),
        .narrow => {
            const bits: u6 = @intCast(inst.aux);
            try writer.writeAll("  {\n");
            try writer.print("    int64_t v = s[{d}];\n", .{inst.src0});
            if (bits < 64) {
                try writer.print("    if ((v >> {d}) != 0) jogrt_panic(jog_narrow_msg, 28);\n", .{bits});
                if (bits == 32) {
                    try writer.print("    s[{d}] = (int64_t)(uint32_t)v;\n", .{inst.dst});
                } else if (bits == 16) {
                    try writer.print("    s[{d}] = (int64_t)(uint16_t)v;\n", .{inst.dst});
                } else if (bits == 8) {
                    try writer.print("    s[{d}] = (int64_t)(uint8_t)v;\n", .{inst.dst});
                } else if (bits == 1) {
                    try writer.print("    s[{d}] = v & 1;\n", .{inst.dst});
                } else {
                    const mask: u64 = (@as(u64, 1) << bits) - 1;
                    try writer.print("    s[{d}] = v & {d}LL;\n", .{ inst.dst, mask });
                }
            } else {
                try writer.print("    s[{d}] = v;\n", .{inst.dst});
            }
            try writer.writeAll("  }\n");
        },
        .gload => try writer.print("  s[{d}] = jog_global_{d};\n", .{ inst.dst, inst.aux }),
        .gstore => try writer.print("  jog_global_{d} = s[{d}];\n", .{ inst.aux, inst.src0 }),
        .gaddr => try writer.print("  s[{d}] = (int64_t)(intptr_t)&jog_global_{d};\n", .{ inst.dst, inst.aux }),
        .add => try writer.print("  s[{d}] = s[{d}] + s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .sub => try writer.print("  s[{d}] = s[{d}] - s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .mul => try writer.print("  s[{d}] = s[{d}] * s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .div => try writer.print("  s[{d}] = s[{d}] / s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .rem => try writer.print("  s[{d}] = s[{d}] % s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .fadd, .fsub, .fmul, .fdiv => {
            const op: []const u8 = switch (inst.op) {
                .fadd => "+",
                .fsub => "-",
                .fmul => "*",
                .fdiv => "/",
                else => unreachable,
            };
            try writer.writeAll("  {\n");
            try writer.writeAll("    double a, b, r;\n");
            try writer.print("    memcpy(&a, &s[{d}], 8);\n", .{inst.src0});
            try writer.print("    memcpy(&b, &s[{d}], 8);\n", .{inst.src1});
            try writer.print("    r = a {s} b;\n", .{op});
            try writer.print("    memcpy(&s[{d}], &r, 8);\n", .{inst.dst});
            try writer.writeAll("  }\n");
        },
        .sitofp => {
            try writer.writeAll("  {\n");
            try writer.writeAll("    double r;\n");
            try writer.print("    r = (double)s[{d}];\n", .{inst.src0});
            try writer.print("    memcpy(&s[{d}], &r, 8);\n", .{inst.dst});
            try writer.writeAll("  }\n");
        },
        .fptosi => {
            try writer.writeAll("  {\n");
            try writer.writeAll("    double a;\n");
            try writer.print("    memcpy(&a, &s[{d}], 8);\n", .{inst.src0});
            try writer.print("    s[{d}] = (int64_t)a;\n", .{inst.dst});
            try writer.writeAll("  }\n");
        },
        .and_op, .or_op => try writer.writeAll("  /* short-circuit lowered in IR */ abort();\n"),
        .bit_and => try writer.print("  s[{d}] = s[{d}] & s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .bit_or => try writer.print("  s[{d}] = s[{d}] | s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .bit_xor => try writer.print("  s[{d}] = s[{d}] ^ s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .shl => try writer.print("  s[{d}] = s[{d}] << (s[{d}] & 63);\n", .{ inst.dst, inst.src0, inst.src1 }),
        .shr => try writer.print("  s[{d}] = (int64_t)((uint64_t)s[{d}] >> (s[{d}] & 63));\n", .{ inst.dst, inst.src0, inst.src1 }),
        .eq => try writer.print("  s[{d}] = s[{d}] == s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .ne => try writer.print("  s[{d}] = s[{d}] != s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .lt => try writer.print("  s[{d}] = s[{d}] < s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .le => try writer.print("  s[{d}] = s[{d}] <= s[{d}];\n", .{ inst.dst, inst.src0, inst.src1 }),
        .neg => try writer.print("  s[{d}] = -s[{d}];\n", .{ inst.dst, inst.src0 }),
        .bit_not => try writer.print("  s[{d}] = ~s[{d}];\n", .{ inst.dst, inst.src0 }),
        .call => try emitCall(writer, prog, inst, false),
        .icall => {
            try writer.writeAll("  {\n");
            try writer.print("    int64_t (*fp)() = (int64_t(*)())(intptr_t)s[{d}];\n", .{inst.src0});
            try writer.writeAll("    int64_t r = fp(");
            var i: u8 = 0;
            while (i < inst.arity and i < 8) : (i += 1) {
                if (i > 0) try writer.writeAll(", ");
                try writer.print("s[{d}]", .{inst.args[i]});
            }
            try writer.writeAll(");\n");
            if (inst.dst != ir.none) {
                try writer.print("    s[{d}] = r;\n", .{inst.dst});
            }
            try writer.writeAll("  }\n");
        },
        .vtaddr => try writer.print("  s[{d}] = (int64_t)(intptr_t)(void*)jog_vt_{d};\n", .{ inst.dst, inst.aux }),
        .ret => {
            if (inst.src0 != ir.none) {
                if (is_main) {
                    try writer.print("  return (int)s[{d}];\n", .{inst.src0});
                } else {
                    try writer.print("  return s[{d}];\n", .{inst.src0});
                }
            } else {
                try writer.writeAll("  return 0;\n");
            }
        },
        .jmp => {
            const lab = try labelName(&lbuf, fname, ninst, inst.aux);
            try writer.print("  goto {s};\n", .{lab});
        },
        .jz => {
            const lab = try labelName(&lbuf, fname, ninst, inst.aux);
            try writer.print("  if (s[{d}] == 0) goto {s};\n", .{ inst.src0, lab });
        },
        .panic => {
            try writer.print("  jogrt_panic((const void*)(intptr_t)s[{d}], s[{d}]);\n", .{ inst.src0, inst.src1 });
            try writer.writeAll("  abort();\n");
        },
    }
}

fn emitCall(writer: anytype, prog: *const ir.Program, inst: ir.Inst, _: bool) !void {
    const cid: usize = @intCast(inst.aux);
    const callee = prog.callees[cid];
    try writer.writeAll("  {\n");
    if (callee.kind == .extern_c) {
        // wasm32 ABI: pointers/i32 → intptr_t; i64/u64 → int64_t; floats → double;
        // void returns call without capturing a result.
        const void_ret = callee.void_ret and !callee.float_ret;
        if (callee.float_ret) {
            try writer.writeAll("    double r;\n");
            try writer.writeAll("    r = ((double(*)(");
        } else if (void_ret) {
            try writer.writeAll("    ((void(*)(");
        } else if (callee.wide_ret) {
            try writer.writeAll("    int64_t r;\n");
            try writer.writeAll("    r = ((int64_t(*)(");
        } else {
            try writer.writeAll("    intptr_t r;\n");
            try writer.writeAll("    r = ((intptr_t(*)(");
        }
        var i: u8 = 0;
        while (i < inst.arity and i < 8) : (i += 1) {
            if (i > 0) try writer.writeAll(", ");
            const is_f = (callee.float_args & (@as(u8, 1) << @intCast(i))) != 0;
            const is_w = (callee.wide_args & (@as(u8, 1) << @intCast(i))) != 0;
            if (is_f) {
                try writer.writeAll("double");
            } else if (is_w) {
                try writer.writeAll("int64_t");
            } else {
                try writer.writeAll("intptr_t");
            }
        }
        try writer.print(")){s})(", .{callee.name});
        i = 0;
        while (i < inst.arity and i < 8) : (i += 1) {
            if (i > 0) try writer.writeAll(", ");
            const is_f = (callee.float_args & (@as(u8, 1) << @intCast(i))) != 0;
            const is_w = (callee.wide_args & (@as(u8, 1) << @intCast(i))) != 0;
            if (is_f) {
                try writer.print("*(double*)&s[{d}]", .{inst.args[i]});
            } else if (is_w) {
                try writer.print("s[{d}]", .{inst.args[i]});
            } else {
                try writer.print("(intptr_t)s[{d}]", .{inst.args[i]});
            }
        }
        try writer.writeAll(");\n");
        if (inst.dst != ir.none) {
            if (callee.float_ret) {
                try writer.print("    memcpy(&s[{d}], &r, 8);\n", .{inst.dst});
            } else if (void_ret) {
                try writer.print("    s[{d}] = 0;\n", .{inst.dst});
            } else {
                try writer.print("    s[{d}] = (int64_t)r;\n", .{inst.dst});
            }
        } else if (!void_ret) {
            try writer.writeAll("    (void)r;\n");
        }
    } else if (callee.kind == .runtime and (std.mem.eql(u8, callee.name, "jogrt_print") or std.mem.eql(u8, callee.name, "jogrt_panic") or std.mem.eql(u8, callee.name, "jogrt_print_tid"))) {
        // (ptr, len)
        try writer.print("    {s}((const void*)(intptr_t)s[{d}], s[{d}]);\n", .{ callee.name, inst.args[0], inst.args[1] });
        if (inst.dst != ir.none) try writer.print("    s[{d}] = 0;\n", .{inst.dst});
    } else if (callee.kind == .runtime and std.mem.eql(u8, callee.name, "jogrt_alloc")) {
        try writer.print("    void *p = jogrt_alloc(s[{d}]);\n", .{inst.args[0]});
        if (inst.dst != ir.none) {
            try writer.print("    s[{d}] = (int64_t)(intptr_t)p;\n", .{inst.dst});
        }
    } else if (callee.kind == .runtime and std.mem.eql(u8, callee.name, "jogrt_host_run_loop")) {
        try writer.print("    jogrt_host_run_loop((int64_t(*)(void))(intptr_t)s[{d}]);\n", .{inst.args[0]});
        if (inst.dst != ir.none) try writer.print("    s[{d}] = 0;\n", .{inst.dst});
    } else {
        // Generic int64_t call (Jog fn, most externs, remaining runtime).
        try writer.writeAll("    int64_t r = ");
        try writer.print("{s}(", .{callee.name});
        var i: u8 = 0;
        while (i < inst.arity and i < 8) : (i += 1) {
            if (i > 0) try writer.writeAll(", ");
            // Pass pointers/ints as int64_t; C default promotions + emcc handle ABI.
            try writer.print("s[{d}]", .{inst.args[i]});
        }
        try writer.writeAll(");\n");
        if (inst.dst != ir.none) {
            try writer.print("    s[{d}] = r;\n", .{inst.dst});
        } else {
            try writer.writeAll("    (void)r;\n");
        }
    }
    try writer.writeAll("  }\n");
}
