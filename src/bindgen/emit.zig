//! Render a bindgen Unit as ordinary Jog extern binding source.

const std = @import("std");
const model = @import("model.zig");

pub fn writeUnit(writer: anytype, unit: *const model.Unit, opts: model.Options) !void {
    try writer.writeAll("// Generated by jog bindgen. Edit as needed; not a build artifact.\n");
    try writer.print("// Source: {s}\n", .{opts.header});
    if (opts.prefix.len > 0) {
        try writer.print("// Prefix filter: {s}\n", .{opts.prefix});
    }
    try writer.writeAll("\n");
    try writer.writeAll("import std.c\n\n");

    for (unit.typedefs.items) |td| {
        try writer.print("type {s} = ", .{td.name});
        try writeType(writer, td.ty);
        try writer.writeAll("\n");
    }
    if (unit.typedefs.items.len > 0) try writer.writeAll("\n");

    for (unit.structs.items) |s| {
        if (s.is_union) {
            try writer.writeAll("// bindgen: C union (Jog @union not required for layout-compatible fields)\n");
        }
        if (s.opaque_only) {
            try writer.print("@opaque struct {s}\n\n", .{s.name});
            continue;
        }
        try writer.print("struct {s} {{\n", .{s.name});
        for (s.fields) |f| {
            try writer.print("    {s}: ", .{f.name});
            try writeType(writer, f.ty);
            try writer.writeAll("\n");
        }
        try writer.writeAll("}\n\n");
    }

    for (unit.enums.items) |e| {
        try writer.print("enum {s}: c.int {{\n", .{e.name});
        for (e.variants) |v| {
            try writer.print("    {s} = {d}\n", .{ v.name, v.value });
        }
        try writer.writeAll("}\n\n");
    }

    for (unit.consts.items) |c| {
        if (std.mem.eql(u8, c.ty, "cstr")) {
            try writer.print("val {s}: *const c.char = c\"{s}\"\n", .{ c.name, c.value });
        } else {
            try writer.print("val {s}: {s} = {s}\n", .{ c.name, c.ty, c.value });
        }
    }
    if (unit.consts.items.len > 0) try writer.writeAll("\n");

    if (opts.link) |lib| {
        try writer.print("@link(\"{s}\")\n", .{lib});
    }
    try writer.writeAll("extern {\n");
    for (unit.fns.items) |f| {
        try writer.print("    fn {s}(", .{f.name});
        for (f.params, 0..) |p, i| {
            if (i > 0) try writer.writeAll(", ");
            try writer.print("{s}: ", .{p.name});
            try writeType(writer, p.ty);
        }
        if (f.variadic) {
            if (f.params.len > 0) try writer.writeAll(", ");
            try writer.writeAll("...");
        }
        try writer.writeAll(")");
        if (f.ret) |ret| {
            try writer.writeAll(": ");
            try writeType(writer, ret);
        }
        try writer.writeAll("\n");
    }
    try writer.writeAll("}\n");
}

fn writeType(writer: anytype, ty: model.JogType) !void {
    switch (ty) {
        .named => |n| try writer.writeAll(n),
        .pointer => |p| {
            try writer.writeAll("*");
            if (p.is_const) try writer.writeAll("const ");
            try writeType(writer, p.elem.*);
        },
        .optional_pointer => |p| {
            try writer.writeAll("*");
            if (p.is_const) try writer.writeAll("const ");
            try writeType(writer, p.elem.*);
            try writer.writeAll("?");
        },
        .array => |a| {
            try writer.print("[{d}]", .{a.len});
            try writeType(writer, a.elem.*);
        },
        .fn_ptr => |fp| {
            try writer.writeAll("(");
            for (fp.params, 0..) |pt, i| {
                if (i > 0) try writer.writeAll(", ");
                try writeType(writer, pt);
            }
            try writer.writeAll(") -> ");
            try writeType(writer, fp.ret.*);
        },
        .opaque_ptr => try writer.writeAll("*void"),
    }
}

pub fn writeSkipped(writer: anytype, unit: *const model.Unit) !void {
    if (unit.skipped.items.len == 0) return;
    try writer.writeAll("bindgen: skipped (write by hand):\n");
    for (unit.skipped.items) |s| {
        try writer.print("  {s}: {s}\n", .{ s.name, s.reason });
    }
}

test "emit minimal binding" {
    var unit: model.Unit = .{ .allocator = std.testing.allocator };
    defer unit.deinit();

    const elem = try unit.allocType();
    elem.* = .{ .named = "c.int" };
    var fields = try std.testing.allocator.alloc(model.Field, 2);
    fields[0] = .{ .name = "x", .ty = .{ .named = "c.int" } };
    fields[1] = .{ .name = "y", .ty = .{ .named = "c.int" } };
    try unit.structs.append(std.testing.allocator, .{
        .name = "Point",
        .fields = fields,
    });

    var params = try std.testing.allocator.alloc(model.Param, 2);
    params[0] = .{ .name = "a", .ty = .{ .named = "c.int" } };
    params[1] = .{ .name = "b", .ty = .{ .named = "c.int" } };
    try unit.fns.append(std.testing.allocator, .{
        .name = "sample_add",
        .params = params,
        .ret = .{ .named = "c.int" },
    });

    var buf: std.ArrayListUnmanaged(u8) = .{};
    defer buf.deinit(std.testing.allocator);
    try writeUnit(buf.writer(std.testing.allocator), &unit, .{
        .header = "sample.h",
        .link = "sample",
        .prefix = "sample_",
    });
    const out = buf.items;
    try std.testing.expect(std.mem.indexOf(u8, out, "import std.c") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "struct Point") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "@link(\"sample\")") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "fn sample_add(a: c.int, b: c.int): c.int") != null);
}

test "emit opaque and variadic" {
    var unit: model.Unit = .{ .allocator = std.testing.allocator };
    defer unit.deinit();
    try unit.structs.append(std.testing.allocator, .{
        .name = "Opaque",
        .fields = &.{},
        .opaque_only = true,
    });
    const char_t = try unit.allocType();
    char_t.* = .{ .named = "c.char" };
    var params = try std.testing.allocator.alloc(model.Param, 1);
    params[0] = .{
        .name = "fmt",
        .ty = .{ .pointer = .{ .elem = char_t, .is_const = true } },
    };
    try unit.fns.append(std.testing.allocator, .{
        .name = "sample_log",
        .params = params,
        .ret = null,
        .variadic = true,
    });

    var buf: std.ArrayListUnmanaged(u8) = .{};
    defer buf.deinit(std.testing.allocator);
    try writeUnit(buf.writer(std.testing.allocator), &unit, .{ .header = "sample.h" });
    try std.testing.expect(std.mem.indexOf(u8, buf.items, "@opaque struct Opaque") != null);
    try std.testing.expect(std.mem.indexOf(u8, buf.items, "fn sample_log(fmt: *const c.char, ...)") != null);
}
